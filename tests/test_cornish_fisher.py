"""Tests for src/cornish_fisher.py: Cornish-Fisher capital multiple and the
admissible domain R (Section 3.2.1, Eq. 15-18)."""

import numpy as np
import pytest
from scipy.stats import norm

from src.cornish_fisher import (
    admissible_domain,
    cm_cf,
    fit_sk,
    mu3_cf,
    mu4_cf,
    x_alpha_cf,
)


def test_mu3_cf_zero_at_s_k_zero():
    """At s = k = 0, X reduces to standard normal Z: mu_3 = mu_4 - 3 sigma^4 = 0."""
    assert mu3_cf(0.0, 0.0, 1.0) == pytest.approx(0.0, abs=1e-9)
    assert mu4_cf(0.0, 0.0, 1.0) == pytest.approx(3.0, abs=1e-9)  # excess kurtosis 0


def test_mu3_cf_scales_with_sigma_cubed():
    s, k = 0.1, 0.05
    base = mu3_cf(s, k, 1.0)
    scaled = mu3_cf(s, k, 2.0)
    assert scaled == pytest.approx(base * 2.0 ** 3, rel=1e-8)


def test_cm_cf_reduces_to_u_alpha_at_s_k_zero():
    u_alpha = norm.ppf(0.999)
    assert cm_cf(u_alpha, 0.0, 0.0) == pytest.approx(u_alpha)


def test_admissible_domain_boundaries():
    """s = k = 0 lies on the boundary s^2 = 0, which Eq. 18 excludes
    (0 < s^2 < 3 - 2 sqrt(2)); a small positive skew with k inside the band
    computed from the same formula must be admissible."""
    assert not admissible_domain(0.0, 0.0)
    s = 0.2
    s2 = s ** 2
    discriminant = s ** 4 - 6 * s2 + 1
    k_mid = (1 + 11 * s2) / 6.0
    assert discriminant > 0
    assert admissible_domain(s, k_mid)
    assert not admissible_domain(s, k_mid + 10.0)


def test_fit_sk_recovers_known_moments():
    """Fitting (s, k) by minimising E(s,k) of Eq. (17) against moments
    generated by a known (s, k) pair must drive the objective to (near) zero,
    i.e. the fitted (s, k) must reproduce the target third and fourth central
    moments. The minimiser of Eq. (17) is not guaranteed to be unique in
    (s, k) itself, so only the implied moments are checked."""
    s_true, k_true, sigma = 0.05, 0.01, 0.02
    mu3_target = mu3_cf(s_true, k_true, sigma)
    mu4_target = mu4_cf(s_true, k_true, sigma)
    s_hat, k_hat, residual = fit_sk(mu3_target, mu4_target, sigma)
    assert residual < 1e-6
    assert mu3_cf(s_hat, k_hat, sigma) == pytest.approx(mu3_target, abs=1e-6)
    assert mu4_cf(s_hat, k_hat, sigma) == pytest.approx(mu4_target, abs=1e-6)


def test_x_alpha_cf_matches_cm_cf_definition():
    p0, alpha, s, k, sigma = 0.01, 0.999, 0.02, 0.01, 0.005
    x = x_alpha_cf(p0, alpha, s, k, sigma)
    u_alpha = norm.ppf(alpha)
    expected = p0 + cm_cf(u_alpha, s, k) * sigma
    assert x == pytest.approx(expected)
